// Helper to generate realistic historical OHLC candles for any stock
function generateCandles(basePrice: number, volatility: number = 0.02, days: number = 30): CandlestickData[] {
  const candles: CandlestickData[] = [];
  const today = new Date(2026, 10, 7); // Nov 7, 2026
  let currentClose = basePrice * (1 - volatility * (days / 2));

  for (let i = days; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    // Skip weekends (Saturday=6, Sunday=0)
    if (d.getDay() === 0 || d.getDay() === 6) continue;

    const dateStr = d.toISOString().split('T')[0];
    const dailyChangePct = (Math.random() - 0.48) * volatility * 2;
    const open = Number((currentClose).toFixed(2));
    const close = Number((open * (1 + dailyChangePct)).toFixed(2));
    const high = Number((Math.max(open, close) * (1 + Math.random() * volatility * 0.8)).toFixed(2));
    const low = Number((Math.min(open, close) * (1 - Math.random() * volatility * 0.8)).toFixed(2));
    const volume = Math.floor(500000 + Math.random() * 4500000);

    candles.push({
      time: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });

    currentClose = close;
  }
  return candles;
}

